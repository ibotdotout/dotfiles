# https://obsidian.md/help/sync/headless

npm install -g obsidian-headless

## Login
# ob login

## List your remote vaults
# ob sync-list-remote

## Set up a vault for syncing
# cd ~/vaults/my-vault
# ob sync-setup --vault "My Vault"

## Run a one-time sync
# ob sync

## Run continuous sync (watches for changes)
# ob sync --continuous
